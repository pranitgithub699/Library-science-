# 2. Relevance Judgment Function
def is_relevant(document_text, keywords, threshold=1):
    doc_lower = document_text.lower()
    match_count = sum(1 for kw in keywords if kw.lower() in doc_lower)
    return match_count >= threshold

# 3. Automated Benchmark Engine
def run_ir_benchmark(test_suite, k=3):
    results = []

    for item in test_suite:
        qid = item["id"]
        q_text = item["query"]
        q_type = item["type"]
        keywords = item["relevant_keywords"]

        # --- A. BM25 Retrieval ---
        tokenized_q = q_text.lower().split()
        bm25_scores = real_bm25.get_scores(tokenized_q)
        bm25_indices = sorted(range(len(bm25_scores)), key=lambda i: bm25_scores[i], reverse=True)[:k]

        bm25_relevance = [
            1 if is_relevant(real_documents[idx], keywords) else 0
            for idx in bm25_indices
        ]

        # --- B. Dense Vector Retrieval ---
        vector_docs = real_vector_db.similarity_search(q_text, k=k)
        vector_relevance = [
            1 if is_relevant(doc.page_content, keywords) else 0
            for doc in vector_docs
        ]

        # Calculate Metrics for this Query
        # Precision@K: relevant docs in top K / K
        bm25_p_at_k = sum(bm25_relevance) / k
        vec_p_at_k = sum(vector_relevance) / k

        # Reciprocal Rank (RR): 1 / rank of first relevant doc
        bm25_rr = 0.0
        for rank, rel in enumerate(bm25_relevance, start=1):
            if rel == 1:
                bm25_rr = 1.0 / rank
                break

        vec_rr = 0.0
        for rank, rel in enumerate(vector_relevance, start=1):
            if rel == 1:
                vec_rr = 1.0 / rank
                break

        # Hit@K: binary 1 if at least one relevant document was found in top K
        bm25_hit = 1 if sum(bm25_relevance) > 0 else 0
        vec_hit = 1 if sum(vector_relevance) > 0 else 0

        results.append({
            "Query ID": qid,
            "Type": q_type,
            "Query": q_text[:35] + "...",
            "BM25 P@3": round(bm25_p_at_k, 2),
            "Dense P@3": round(vec_p_at_k, 2),
            "BM25 RR": round(bm25_rr, 2),
            "Dense RR": round(vec_rr, 2),
            "BM25 Hit@3": bm25_hit,
            "Dense Hit@3": vec_hit
        })

    return pd.DataFrame(results)

