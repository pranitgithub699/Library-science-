# 2. The Robust Hybrid Retrieval Function
def reciprocal_rank_fusion(query, k=3, rrf_k=60):
    # --- A. Get BM25 Ranks ---
    tokenized_q = query.lower().split()
    bm25_scores = real_bm25.get_scores(tokenized_q)
    bm25_indices = sorted(range(len(bm25_scores)), key=lambda i: bm25_scores[i], reverse=True)

    # --- B. Get Vector Ranks using Metadata ---
    vector_results = real_vector_db.similarity_search(query, k=50)

    # The fix: Use .get() as a safety net to prevent KeyErrors
    vector_indices = []
    for doc in vector_results:
        idx = doc.metadata.get("original_index")
        if idx is not None:
            vector_indices.append(idx)

    # --- C. Apply RRF Formula: Score = 1 / (rrf_k + rank) ---
    fusion_scores = {}

    for rank, doc_idx in enumerate(bm25_indices):
        fusion_scores[doc_idx] = fusion_scores.get(doc_idx, 0) + 1.0 / (rrf_k + rank + 1)

    for rank, doc_idx in enumerate(vector_indices):
        fusion_scores[doc_idx] = fusion_scores.get(doc_idx, 0) + 1.0 / (rrf_k + rank + 1)

    # --- D. Sort by the new fused score ---
    top_fused_indices = sorted(fusion_scores.keys(), key=lambda idx: fusion_scores[idx], reverse=True)[:k]

    print(f"\n=== HYBRID RRF SEARCH RESULTS FOR: '{query}' ===")
    for rank, idx in enumerate(top_fused_indices):
        score = fusion_scores[idx]
        snippet = real_documents[idx].replace('\n', ' ')[:200]
        print(f"Rank {rank+1} (RRF Score: {score:.4f}): {snippet}...")

