def run_final_benchmark(test_suite, k=3, rrf_k=60):
    results = []

    for item in test_suite:
        qid = item["id"]
        q_text = item["query"]
        keywords = item["relevant_keywords"]

        # --- A. BM25 ---
        tokenized_q = q_text.lower().split()
        bm25_scores = real_bm25.get_scores(tokenized_q)
        bm25_indices = sorted(range(len(bm25_scores)), key=lambda i: bm25_scores[i], reverse=True)
        bm25_top = bm25_indices[:k]
        bm25_rel = [1 if is_relevant(real_documents[idx], keywords) else 0 for idx in bm25_top]

        # --- B. Vector ---
        vector_results = real_vector_db.similarity_search(q_text, k=50)
        vector_indices = [doc.metadata.get("original_index") for doc in vector_results if doc.metadata.get("original_index") is not None]
        vec_top = vector_indices[:k]
        vec_rel = [1 if is_relevant(real_documents[idx], keywords) else 0 for idx in vec_top]

        # --- C. Hybrid RRF ---
        fusion_scores = {}
        for rank, doc_idx in enumerate(bm25_indices):
            fusion_scores[doc_idx] = fusion_scores.get(doc_idx, 0) + 1.0 / (rrf_k + rank + 1)
        for rank, doc_idx in enumerate(vector_indices):
            fusion_scores[doc_idx] = fusion_scores.get(doc_idx, 0) + 1.0 / (rrf_k + rank + 1)

        hybrid_top = sorted(fusion_scores.keys(), key=lambda idx: fusion_scores[idx], reverse=True)[:k]
        hybrid_rel = [1 if is_relevant(real_documents[idx], keywords) else 0 for idx in hybrid_top]

        # Calculate P@3
        results.append({
            "Query ID": qid,
            "Query Type": item["type"],
            "BM25 P@3": sum(bm25_rel) / k,
            "Vector P@3": sum(vec_rel) / k,
            "Hybrid P@3": sum(hybrid_rel) / k
        })

    return pd.DataFrame(results)

